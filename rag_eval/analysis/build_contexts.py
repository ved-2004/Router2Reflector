"""Build LLM context files for Stage 2 and write them to rag_eval/results/contexts/{split}/{option}.json
({row_id: context_string}) plus {option}.passages.json (the passages placed in the context, for the NLI gate).
Upload afterwards with:  modal volume put -f r2r-rag-eval rag_eval/results/contexts /contexts

Options:
  <retrieval config>  e.g. wiki_hybrid_rr, med_hybrid_rr, arc_bm25_rr  (top-3 passages; ARC sentences top-5)
  <cfg>__L3000        same, 3000-char limit (longer-context variant, top-5 passages)
  gen<SIZE>           R5: background facts generated by Qwen2.5-<SIZE> (gen32B = shared generator)
  oracle_sciq         R6: SciQ gold support passage (other sources: empty -> fall back to direct)
Run: <venv>/bin/python rag_eval/analysis/build_contexts.py cfg1 cfg2 ...
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import RES, build_context, configs_for_corpus, load_split  # noqa

SPLITS = ["validation", "test"]


def main(names):
    out_dir = RES / "contexts"
    corpora = {n.split("__")[0].split("_")[0] for n in names if not n.startswith(("gen", "oracle"))}
    cfgs = {}
    for c in corpora:
        cfgs.update(configs_for_corpus(c))
    for sp in SPLITS:
        rows = load_split(sp)
        (out_dir / sp).mkdir(parents=True, exist_ok=True)
        for name in names:
            ctx, used = {}, {}
            if name.startswith("gen"):
                g = {}
                for f in sorted((RES / "gen" / f"qwen{name[3:]}" / sp).glob("rows*.json")):
                    g.update(json.loads(f.read_text()))
                assert len(g) == len(rows), (name, sp, len(g))
                for r in rows:
                    t = g[str(r["row_id"])].strip()
                    ctx[str(r["row_id"])] = t[:1500]
                    used[str(r["row_id"])] = [{"title": "", "text": t[:1500]}]
            elif name == "oracle_sciq":
                for r in rows:
                    if r["source"] == "SciQ" and r["context"]:
                        ctx[str(r["row_id"])] = r["context"][:1500]
                        used[str(r["row_id"])] = [{"title": "", "text": r["context"][:1500]}]
            else:
                base, _, var = name.partition("__")
                k = 5 if base.startswith("arc") else 3
                limit = 1500
                if var == "L3000":
                    k, limit = (8 if base.startswith("arc") else 5), 3000
                per = cfgs[base][sp]
                for r in rows:
                    ps = per.get(r["row_id"], [])
                    c = build_context(ps, k, limit)
                    if c:
                        ctx[str(r["row_id"])] = c
                        used[str(r["row_id"])] = [{"title": p["title"], "text": p["text"]} for p in ps[:k]]
            (out_dir / sp / f"{name}.json").write_text(json.dumps(ctx))
            (out_dir / sp / f"{name}.passages.json").write_text(json.dumps(used))
            print(sp, name, "rows with ctx:", len(ctx))


if __name__ == "__main__":
    main(sys.argv[1:])
